//! Perceptually uniform colormaps for heatmap visualization

use ratatui::style::Color;

/// Available colormaps
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Colormap {
    Inferno,
    Plasma,
    Viridis,
    Magma,
}

impl Colormap {
    /// Get the name of this colormap
    pub fn name(&self) -> &'static str {
        match self {
            Colormap::Inferno => "Inferno",
            Colormap::Plasma => "Plasma",
            Colormap::Viridis => "Viridis",
            Colormap::Magma => "Magma",
        }
    }

    /// Convert a normalized value (0.0 to 1.0) to an RGB color
    pub fn to_color(&self, value: f32) -> Color {
        let v = value.clamp(0.0, 1.0);
        let idx = (v * 255.0) as usize;
        let (r, g, b) = match self {
            Colormap::Inferno => INFERNO[idx],
            Colormap::Plasma => PLASMA[idx],
            Colormap::Viridis => VIRIDIS[idx],
            Colormap::Magma => MAGMA[idx],
        };
        Color::Rgb(r, g, b)
    }

    /// Get the darkest color (for background)
    pub fn background(&self) -> Color {
        self.to_color(0.0)
    }
}

